import streamlit as st
import folium
from streamlit_folium import st_folium

# 1. வெப்சைட் தலைப்பு
st.title("🚌 நம்ம ஊர் Live Bus Tracker")
st.write("லோக்கல் பஸ் முதல் சிட்டி பஸ் வரை எந்த ஊர் கிட்ட வருது என்று லைவாகப் பார்க்கவும்!")

# 2. தமிழ்நாடு முக்கிய ஊர்களின் GPS விபரங்கள்
ஊர்கள்_GPS = {
    "சென்னை (கோயம்பேடு)": [13.0694, 80.1948],
    "தாம்பரம்": [12.9249, 80.1000],
    "செங்கல்பட்டு": [12.6819, 79.9888],
    "விழுப்புரம்": [11.9401, 79.4861],
    "திருச்சி": [10.7905, 78.7047]
}

# 3. பயனர் ஊர் பெயரைத் தேடும் பகுதி
தேர்ந்தெடுத்த_ஊர் = st.selectbox("நீங்கள் செல்ல வேண்டிய ஊரைத் தேர்ந்தெடுக்கவும்:", list(ஊர்கள்_GPS.keys()))

# 4. அந்த ஊரில் பஸ் இருக்கும் இடத்தை மேப்பில் காட்டுகிறோம்
if தேர்ந்தெடுத்த_ஊர்:
    பஸ்_இடம் = ஊர்கள்_GPS[தேர்ந்தெடுத்த_ஊர்]
    st.success(f"📍 பேருந்து எண் 101: இப்போது '{தேர்ந்தெடுத்த_ஊர்}' அருகே வந்து கொண்டிருக்கிறது!")
    
    # மேப் உருவாக்குதல்
    bus_map = folium.Map(location=பஸ்_இடம், zoom_start=14)
    folium.Marker(
        location=பஸ்_இடம்,
        popup=f"🚌 {தேர்ந்தெடுத்த_ஊர்} பேருந்து",
        icon=folium.Icon(color="red", icon="bus", prefix="fa")
    ).add_to(bus_map)
    
    # திரையில் மேப்பைக் காட்டுதல்
    st_folium(bus_map, width=700, height=400)
